export const CLASS_MAP = Object.fromEntries(PROJECT.classes.map(c => [c.id, c]));
export const CLASS_IDS = PROJECT.classes.map(c => c.id);
export const POSITIVE_IDS = PROJECT.classes.filter(c => c.kind === 'positive').map(c => c.id);
export const NEGATIVE_IDS = PROJECT.classes.filter(c => c.kind === 'negative').map(c => c.id);
export const INVALID_IDS = PROJECT.classes.filter(c => c.kind === 'invalid').map(c => c.id);

/** 클래스 정의를 찾지 못한 경우에도 UI가 깨지지 않도록 하는 폴백 */
export function classOf(id) {
  return CLASS_MAP[id] || {
    id, label: id, labelEn: '', kind: 'negative', color: '#7C8894',
    advice: '이 클래스는 project.config.js에 정의되어 있지 않습니다.',
  };
}

/** 막대·표에 쓰는 병기 표기 — "정상 · Normal" */
/** 데이터셋 정보가 채워졌는지 (플레이스홀더가 그대로면 false) */
export function datasetFilled() {
  const d = PROJECT.dataset;
  return !!d.name && !d.name.startsWith('(');
}

export function fullLabel(id) {
  const c = classOf(id);
  return c.labelEn ? `${c.label} · ${c.labelEn}` : c.label;
}
